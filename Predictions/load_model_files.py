import joblib
import os
import pandas as pd

def load_model_artifacts():
    """
    Load the saved model and related artifacts (scaler, feature columns, numeric columns).
    These artifacts are expected to be generated by main.py.
    """
    project_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    pkl_dir = os.path.join(project_dir, 'pkl')
    
    model_path = os.path.join(pkl_dir, 'ForecaSteam.pkl')
    feature_columns_path = os.path.join(pkl_dir, 'feature_columns.pkl')
    numeric_columns_path = os.path.join(pkl_dir, 'numeric_columns.pkl')
    scaler_path = os.path.join(pkl_dir, 'scaler.pkl')

    try:
        model = joblib.load(model_path)
        feature_columns = joblib.load(feature_columns_path)
        numeric_columns = joblib.load(numeric_columns_path)
        scaler = joblib.load(scaler_path)
        
        print("Model, feature columns, numeric columns, and scaler loaded successfully.")
        # For a regressor, a label_encoder for the target is not typically loaded this way.
        # If one were used for features pre-training, it would be part of the preprocessing pipeline.
        return model, feature_columns, numeric_columns, scaler
    
    except FileNotFoundError as e:
        print(f"Error loading model artifact: {e}")
        print(f"Missing file: {e.filename}")
        print("Please ensure main.py has been run successfully to generate all .pkl files in the 'pkl' directory:")
        print(f"  - {model_path}")
        print(f"  - {feature_columns_path}")
        print(f"  - {numeric_columns_path}")
        print(f"  - {scaler_path}")
        return None, None, None, None
    except Exception as e:
        print(f"An unexpected error occurred while loading model artifacts: {e}")
        import traceback
        traceback.print_exc()
        return None, None, None, None


if __name__ == "__main__":
    model, feature_columns, numeric_columns, scaler = load_model_artifacts()
    
    if model:
        print("\nModel type:", type(model).__name__)
    if feature_columns:
        print(f"\nTotal feature columns expected by model: {len(feature_columns)}")
        print(f"First 5 feature columns: {feature_columns[:5]}")
        if len(feature_columns) > 5:
            print(f"Last 5 feature columns: {feature_columns[-5:]}")
    
    if numeric_columns:
        print(f"\nNumeric columns that were scaled: {len(numeric_columns)}")
        print(f"First 5 numeric columns: {numeric_columns[:5]}")
        if len(numeric_columns) > 5:
            print(f"Last 5 numeric columns: {numeric_columns[-5:]}")
    
    if scaler:
        print("\nScaler loaded:", type(scaler).__name__)